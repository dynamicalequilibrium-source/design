"""Run against disposable DB/API on :8000 and Vite on :3000."""
from playwright.sync_api import sync_playwright, expect
from uuid import uuid4
import os

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.getenv('BATON_CHROMIUM', '/usr/bin/chromium'), headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    failures = []
    page.on('pageerror', lambda e: failures.append(str(e)))
    page.goto('http://127.0.0.1:3000')
    trigger = page.locator('[id^="sentence-"]').first
    expect(trigger).to_be_visible()
    sentence_id = trigger.get_attribute('id')
    trigger.dblclick()
    page.wait_for_timeout(400)
    expect(page.get_by_role('dialog')).to_have_count(0)
    page.evaluate('getSelection().removeAllRanges()')
    trigger.click()
    dialog = page.get_by_role('dialog')
    expect(dialog).to_be_visible()
    page.get_by_role('button', name='새 질문 등록', exact=True).click()
    title = '브라우저 검증 ' + uuid4().hex[:8]
    title_input = page.get_by_placeholder('궁금한 핵심 내용을', exact=False)
    detail = page.get_by_placeholder('실제 마주친 상황', exact=False)
    title_input.fill(title)
    detail.fill('새로고침 뒤에도 작성 내용과 서버 질문이 유지되어야 합니다.')
    page.reload()
    page.locator(f'[id="{sentence_id}"]').click()
    page.get_by_role('button', name='새 질문 등록', exact=True).click()
    expect(title_input).to_have_value(title)
    page.route('**/api/mutations', lambda route: route.abort())
    page.get_by_role('button', name='바통 질문 등록하기', exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('입력 내용은 유지됩니다')
    expect(title_input).to_have_value(title)
    page.unroute('**/api/mutations')
    page.get_by_role('button', name='바통 질문 등록하기', exact=True).click()
    expect(page.get_by_role('combobox', name='연결된 질문 선택')).to_contain_text(title)
    page.get_by_role('button', name='답변 작성하기', exact=True).click()
    page.get_by_placeholder('후임자가 바로 업무에', exact=False).fill('서버에 저장하는 브라우저 답변')
    page.get_by_placeholder('예: 2026 국고보조금', exact=False).fill('가상 근거')
    page.get_by_role('button', name='답변 등록하기', exact=True).click()
    expect(dialog).to_contain_text('서버에 저장하는 브라우저 답변')
    expect(dialog).to_contain_text('사용자 입력 근거 · 확인 필요')
    page.get_by_role('button', name='댓글 0', exact=True).click()
    page.get_by_placeholder('선배님께 추가 질문', exact=False).fill('서버에 저장하는 브라우저 댓글')
    page.get_by_role('button', name='등록', exact=True).click()
    expect(dialog).to_contain_text('서버에 저장하는 브라우저 댓글')
    page.get_by_title('닫기 (ESC)').click()
    expect(page.locator(f'[id="{sentence_id}"]')).to_be_focused()
    page.reload()
    page.locator(f'[id="{sentence_id}"]').click()
    expect(page.get_by_role('combobox', name='연결된 질문 선택')).to_contain_text(title)
    page.get_by_role('combobox', name='연결된 질문 선택').select_option(label=title)
    expect(dialog).to_contain_text('서버에 저장하는 브라우저 답변')
    page.get_by_role('button', name='댓글 1', exact=True).click()
    expect(dialog).to_contain_text('서버에 저장하는 브라우저 댓글')
    page.keyboard.press('Escape')
    expect(dialog).to_have_count(0)
    expect(page.locator(f'[id="{sentence_id}"]')).to_be_focused()
    page.set_viewport_size({'width': 390, 'height': 844})
    page.locator(f'[id="{sentence_id}"]').click()
    expect(dialog).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'horizontal overflow'
    assert not failures, failures
    browser.close()
    print('PASS: double click, draft recovery, failed save, registration, reload persistence, focus return, narrow screen, no runtime errors')
